export function normalizeRoomTier(raw: unknown): RoomTier {
  const val = String(raw ?? '').trim().toLowerCase();
  if (val === 'tipe c' || val === 'corner suite') return 'Tipe C';
  if (val === 'tipe b' || val === 'deluxe ac') return 'Tipe B';
  return 'Tipe A';
}

export function getRoomDisplayName(room: { name?: string; number: string }): string {
  const custom = room.name?.trim();
  return custom ? custom : `Kamar ${room.number}`;
}

